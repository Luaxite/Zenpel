"""`#[bind(serde)]` (S41-S43): your own serde types as parameters and returns of a bound fn (tools/bind_serde.py, bind_attrs.py, hooks in bind_scan.py and bind_gen.py).
S40 is the manifest check at the end: mlua's `serialize` feature and a `serde` dependency with `derive`."""
import contextlib
import io
import re
import tempfile
import tomllib
import unittest
from pathlib import Path

import _common
import bind_attrs
import bind_gen
import bind_scan
import bind_serde

HEAD = "// @generated by tools/bind_gen.py: do not edit.\npub fn register(lua: &mlua::Lua) -> mlua::Result<()> {\n    let globals = lua.globals();\n"
OPTS = "mlua::serde::SerializeOptions::new().serialize_none_to_null(false).serialize_unit_to_null(false)"
FROM = "let a0 = mlua::LuaSerdeExt::from_value(lua, a0)?; "


def gen(src):
    """(text, stderr) for a one-file tree rust/main.rs."""
    with tempfile.TemporaryDirectory() as d:
        Path(d, "rust").mkdir()
        Path(d, "rust", "main.rs").write_text(src)
        err = io.StringIO()
        with contextlib.redirect_stderr(err):
            text = bind_gen.generate(d)
    return text, err.getvalue()


def only(src):
    """The one `globals.set` line a single `#[bind(serde)]` fn produces (no stderr allowed)."""
    text, err = gen(src)
    assert err == "", err
    assert text.startswith(HEAD) and text.endswith("    Ok(())\n}\n"), text
    return text[len(HEAD) : -len("    Ok(())\n}\n")]


RET = f"mlua::LuaSerdeExt::to_value_with(lua, &r, {OPTS})"


class Attrs(unittest.TestCase):
    def test_serde_key(self):
        for body, want in (
            ("bind", {"raw": False, "serde": False}),
            ("bind(serde)", {"raw": False, "serde": True}),
            ("zenpel_bind::bind(serde)", {"raw": False, "serde": True}),
            ('bind("a.b", serde)', {"raw": False, "serde": True}),
            ("bind(serde,)", {"raw": False, "serde": True}),
            ("bind(raw)", {"raw": True, "serde": False}),
            ("bind(raw, serde)", {"raw": True, "serde": True}),
            ('bind("serde")', {"raw": False, "serde": False}),  # a string is not the key
            ('bind("a,serde")', {"raw": False, "serde": False}),  # nor is a comma inside a string
            ("bind(serdes)", {"raw": False, "serde": False}),
        ):
            with self.subTest(body):
                self.assertEqual(bind_attrs.parse([body]), want)

    def test_first_bind_that_names_an_option_wins_and_others_are_ignored(self):
        self.assertEqual(bind_attrs.parse(["inline", "bind", "bind(serde)"]), {"raw": False, "serde": True})
        self.assertEqual(bind_attrs.parse(["derive(Debug)"]), {"raw": False, "serde": False})
        self.assertEqual(bind_attrs.parse([]), {"raw": False, "serde": False})


class Scan(unittest.TestCase):
    def test_json_key_serde_and_raw(self):
        src = "#[bind(serde)]\nfn a(c: Config) {}\n#[bind]\nfn b() {}\n#[bind(raw, serde)]\nfn c() {}\n"
        got = {r[2]: (r[5]["serde"], r[5]["raw"]) for r in bind_scan.scan_text(src, "rust/t.rs")}
        self.assertEqual(got, {"a": (True, False), "b": (False, False), "c": (True, True)})


class Helpers(unittest.TestCase):
    known = staticmethod(lambda t: t in bind_gen.PRIMS)

    def test_path_type(self):
        for ty in ("Config", "crate::Config", "a::b::Config", "::a::Config"):
            self.assertTrue(bind_serde.path_type(ty), ty)
        for ty in ("&Config", "Self", "()", "(A, B)", "Vec<A>", "", "[u8; 3]", "dyn A"):
            self.assertFalse(bind_serde.path_type(ty), ty)

    def test_unknown(self):
        k = self.known
        for ty in ("Config", "crate::Config", "Option<Config>", "Vec<Config>", "Vec<Option<Config>>", "Option<Vec<Config>>"):
            self.assertTrue(bind_serde.unknown(ty, k), ty)
        for ty in ("i32", "String", "Option<i32>", "Vec<String>", "&Config", "Option<Option<Config>>", "(Config, Config)", "Result<Config, E>", "()", ""):
            self.assertFalse(bind_serde.unknown(ty, k), ty)

    def test_ret_inner(self):
        for ty, want in (("Result<Config, String>", "Config"), ("anyhow::Result<Config>", "Config"), ("mlua::Result<Vec<A>>", "Vec<A>"), ("Config", "Config"), ("Result<Vec<(A, B)>, E>", "Vec<(A, B)>")):
            self.assertEqual(bind_serde.ret_inner(ty), want)


class Text(unittest.TestCase):
    """S41: exact text for a bare path type."""

    def test_argument(self):
        self.assertEqual(only("#[bind(serde)]\nfn area(c: Config) -> f64 { 0.0 }\n"), f'    globals.set("area", lua.create_function(|lua, a0: mlua::Value| {{ {FROM}Ok(crate::area(a0)) }})?)?;\n')

    def test_return(self):
        want = f'    globals.set("make", lua.create_function(|lua, a0: i32| {{ let r = crate::make(a0); {RET} }})?)?;\n'
        self.assertEqual(only("#[bind(serde)]\nfn make(n: i32) -> Config { todo!() }\n"), want)

    def test_qualified_paths_and_a_plain_arg_next_to_a_serde_one(self):
        want = f'    globals.set("f", lua.create_function(|lua, (a0, a1): (mlua::Value, i32)| {{ {FROM}let r = crate::f(a0, a1); {RET} }})?)?;\n'
        self.assertEqual(only("#[bind(serde)]\nfn f(c: crate::a::Config, k: i32) -> b::Reply { todo!() }\n"), want)

    def test_two_serde_args(self):
        got = only("#[bind(serde)]\nfn f(a: A, b: B) {}\n")
        self.assertIn("(a0, a1): (mlua::Value, mlua::Value)", got)
        self.assertIn("let a0 = mlua::LuaSerdeExt::from_value(lua, a0)?; let a1 = mlua::LuaSerdeExt::from_value(lua, a1)?; Ok(crate::f(a0, a1))", got)

    def test_the_type_is_never_spelled(self):
        # it resolves where the user wrote it, not in crate::luau: `from_value` takes T from the callee's parameter
        got = only("#[bind(serde)]\nfn f(c: Config, d: Vec<Option<Other>>) -> Reply { todo!() }\n")
        for name in ("Config", "Other", "Reply"):
            self.assertNotIn(name, got)
        self.assertNotIn("from_value::<", got)

    def test_none_and_unit_become_nil(self):
        self.assertIn("serialize_none_to_null(false)", bind_serde.OPTIONS)
        self.assertIn("serialize_unit_to_null(false)", bind_serde.OPTIONS)

    def test_a_known_type_in_a_serde_fn_is_plain(self):
        want = '    globals.set("p", lua.create_function(|_, (a0, a1): (i32, Option<String>)| Ok(crate::p(a0, a1)))?)?;\n'
        self.assertEqual(only("#[bind(serde)]\nfn p(a: i32, b: Option<String>) -> bool { true }\n"), want)

    def test_lua_first_param_is_still_injected(self):
        got = only("#[bind(serde)]\nfn f(lua: &mlua::Lua, c: Config) {}\n")
        self.assertIn(f"|lua, a0: mlua::Value| {{ {FROM}Ok(crate::f(lua, a0)) }}", got)

    def test_cfg_block(self):
        text, _ = gen('#[cfg(feature = "x")]\n#[bind(serde)]\nfn f(c: Config) {}\n')
        self.assertIn('    #[cfg(feature = "x")]\n    {\n        globals.set("f", lua.create_function(|lua, a0: mlua::Value| {', text)

    def test_without_serde_the_text_is_what_it_was(self):
        src = "#[bind]\nfn a(x: i32, y: Option<String>) -> String { todo!() }\n#[bind]\nfn b() {}\n#[bind]\nfn c(lua: &mlua::Lua, n: u8) -> anyhow::Result<bool> { Ok(true) }\n"
        text, err = gen(src)
        self.assertEqual(err, "")
        self.assertNotIn("LuaSerdeExt", text)
        self.assertIn('lua.create_function(|_, (a0, a1): (i32, Option<String>)| Ok(crate::a(a0, a1)))', text)
        self.assertIn('lua.create_function(|_, ()| Ok(crate::b()))', text)
        self.assertIn("|lua, a0: u8| crate::c(lua, a0).map_err(|e| mlua::Error::runtime(e.to_string()))", text)

    def test_without_serde_an_own_type_is_unsupported_as_before(self):
        text, err = gen("#[bind]\nfn f(c: Config) {}\n#[bind]\nfn g() -> Config { todo!() }\n")
        self.assertEqual(err, "unsupported rust/main.rs:2 f Config\nunsupported rust/main.rs:4 g Config\n")
        self.assertNotIn("globals.set", text)


class Wrapped(unittest.TestCase):
    """S42: Option, Vec and Result around the serde type."""

    def test_option_argument_and_return(self):
        want = f'    globals.set("f", lua.create_function(|lua, a0: mlua::Value| {{ {FROM}let r = crate::f(a0); {RET} }})?)?;\n'
        self.assertEqual(only("#[bind(serde)]\nfn f(c: Option<Config>) -> Option<Reply> { todo!() }\n"), want)

    def test_vec_nested_in_option_and_option_in_vec(self):
        got = only("#[bind(serde)]\nfn f(a: Vec<Config>, b: Option<Vec<Config>>) -> Vec<Option<Reply>> { todo!() }\n")
        self.assertIn("(a0, a1): (mlua::Value, mlua::Value)", got)
        self.assertIn("let r = crate::f(a0, a1);", got)

    def test_result_err_raises_ok_goes_through_serde(self):
        err = ".map_err(|e| mlua::Error::runtime(e.to_string()))"
        for ret_ty in ("Result<Reply, String>", "anyhow::Result<Reply>", "mlua::Result<Reply>", "std::result::Result<Reply, std::io::Error>"):
            with self.subTest(ret_ty):
                want = f'    globals.set("f", lua.create_function(|lua, a0: i32| {{ let r = crate::f(a0){err}?; {RET} }})?)?;\n'
                self.assertEqual(only(f"#[bind(serde)]\nfn f(n: i32) -> {ret_ty} {{ todo!() }}\n"), want)

    def test_result_of_option_and_vec(self):
        got = only("#[bind(serde)]\nfn f(c: Config) -> Result<Option<Vec<Reply>>, String> { todo!() }\n")
        self.assertIn("let r = crate::f(a0).map_err(|e| mlua::Error::runtime(e.to_string()))?;", got)

    def test_result_of_a_plain_type_is_not_a_serde_return(self):
        got = only("#[bind(serde)]\nfn f(c: Config) -> Result<String, String> { todo!() }\n")
        self.assertNotIn("to_value", got)
        self.assertTrue(got.rstrip().endswith("crate::f(a0).map_err(|e| mlua::Error::runtime(e.to_string())) })?)?;"), got)

    def test_unit_result_with_a_serde_arg(self):
        got = only("#[bind(serde)]\nfn f(c: Config) -> anyhow::Result<()> { todo!() }\n")
        self.assertIn(f"{{ {FROM}crate::f(a0).map_err(|e| mlua::Error::runtime(e.to_string())) }}", got)

    def test_what_stays_unsupported_with_serde(self):
        src = "".join(f"#[bind(serde)]\nfn f{i}(c: {ty}) {{}}\n" for i, ty in enumerate(("&Config", "(Config, Config)", "Option<Option<Config>>", "Wrapper<Config>", "Vec<i32>", "Option<&str>")))
        src += "#[bind(serde)]\nfn r() -> &Config { todo!() }\n#[bind(serde)]\nfn t() -> (Config, i32) { todo!() }\n#[bind(serde)]\nfn o() -> Option<Option<Config>> { todo!() }\n"
        text, err = gen(src)
        self.assertNotIn("globals.set", text)
        for n, ty in ((2, "&Config"), (4, "(Config, Config)"), (6, "Option<Option<Config>>"), (8, "Wrapper<Config>"), (10, "Vec<i32>"), (12, "Option<&str>")):
            self.assertIn(f"unsupported rust/main.rs:{n} f{(n - 2) // 2} {ty}\n", err)
        for n, name, ty in ((14, "r", "&Config"), (16, "t", "(Config, i32)"), (18, "o", "Option<Option<Config>>")):
            self.assertIn(f"unsupported rust/main.rs:{n} {name} {ty}\n", err)


class Conflict(unittest.TestCase):
    """S43: `raw` and `serde` on one attribute."""

    SRC = "#[bind(raw, serde)]\nfn f(c: Config) {}\n"

    def test_the_fn_is_left_out_with_a_note(self):
        text, err = gen(self.SRC)
        self.assertEqual(err, "conflict rust/main.rs:2 f raw+serde\n")
        self.assertNotIn("globals.set", text)

    def test_the_name_is_not_claimed(self):
        text, err = gen(self.SRC + "#[bind(serde)]\nfn f(c: Config) {}\n")
        self.assertEqual(err, "conflict rust/main.rs:2 f raw+serde\n")
        self.assertEqual(text.count("globals.set"), 1)
        self.assertIn("LuaSerdeExt", text)

    def test_the_other_fns_are_still_bound(self):
        text, err = gen(self.SRC + "#[bind]\nfn g(a: i32) {}\n")
        self.assertEqual(err, "conflict rust/main.rs:2 f raw+serde\n")
        self.assertIn("crate::g(a0)", text)

    def test_either_alone_is_no_conflict(self):
        text, err = gen("#[bind(raw)]\nfn a(x: i32) {}\n#[bind(serde)]\nfn b(c: Config) {}\n")
        self.assertEqual(err, "")
        self.assertEqual(text.count("globals.set"), 2)

    def test_the_cli_prints_it(self):
        with tempfile.TemporaryDirectory() as d:
            Path(d, "rust").mkdir()
            Path(d, "rust", "main.rs").write_text(self.SRC)
            p = _common.run(["python3", _common.TOOLS / "bind_gen.py", "--root", d])
        self.assertEqual(p.returncode, 0)
        self.assertEqual(p.stderr, "conflict rust/main.rs:2 f raw+serde\n")


class Manifest(unittest.TestCase):
    """S40: what the generated code needs from Cargo.toml."""

    def setUp(self):
        self.deps = tomllib.loads(_common.read("Cargo.toml"))["dependencies"]

    def test_mlua_has_serialize_and_keeps_the_rest(self):
        self.assertEqual(set(self.deps["mlua"]["features"]), {"luau", "async", "send", "macros", "serialize"})
        self.assertEqual(self.deps["mlua"]["version"], "0.12")

    def test_serde_with_derive(self):
        self.assertEqual(self.deps["serde"]["version"], "1")
        self.assertIn("derive", self.deps["serde"]["features"])

    def test_the_generated_glue_names_only_what_the_feature_provides(self):
        text = only("#[bind(serde)]\nfn f(c: Config) -> Config { todo!() }\n")
        self.assertEqual(sorted(set(re.findall(r"mlua::[A-Za-z_:]+", text))), ["mlua::LuaSerdeExt::from_value", "mlua::LuaSerdeExt::to_value_with", "mlua::Value", "mlua::serde::SerializeOptions::new"])


